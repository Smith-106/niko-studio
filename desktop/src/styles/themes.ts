export function getThemeDefinition(id: ThemeId): ThemeDefinition {
  if (id === 'system') {
    const prefersDark = window.matchMedia('(prefers-color-scheme: dark)').matches
    return prefersDark ? THEMES.slate : THEMES.sorbet
  }
  return THEMES[id]
}
